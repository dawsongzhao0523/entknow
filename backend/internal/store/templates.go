// ListTemplates 返回全部 29 句话模板。
func (s *Store) ListTemplates() []Template { return Templates }

// TemplateCategories 7 个分类及其中模板数。
func TemplateCategories() []map[string]any {
	order := []string{"业务术语", "业务资源描述", "业务分层约束", "业务控制规则", "流程活动与业务操作", "权限管控", "数据操作"}
	byCat := map[string][]Template{}
	for _, t := range Templates {
		byCat[t.Category] = append(byCat[t.Category], t)
	}
	out := []map[string]any{}
	for _, c := range order {
		out = append(out, map[string]any{"category": c, "standard": byCat[c][0].Standard, "count": len(byCat[c])})
	}
	return out
}
